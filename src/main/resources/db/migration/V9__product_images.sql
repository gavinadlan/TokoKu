CREATE TABLE product_images (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    public_id  VARCHAR(255),                     -- NULL = gambar eksternal (hasil migrasi image_url lama)
    url        VARCHAR(600) NOT NULL,            -- URL dasar; ukuran bernama dibangun dari sini
    width      INTEGER,
    height     INTEGER,
    position   INTEGER      NOT NULL,
    is_primary BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_product_images_product ON product_images (product_id, position);
CREATE UNIQUE INDEX uq_product_images_public_id ON product_images (public_id) WHERE public_id IS NOT NULL;
CREATE UNIQUE INDEX uq_product_images_one_primary ON product_images (product_id) WHERE is_primary;

-- Migrasi image_url lama menjadi baris gambar eksternal (utama). Kolom products.image_url dibiarkan (tidak dipakai lagi).
INSERT INTO product_images (product_id, public_id, url, position, is_primary)
SELECT id, NULL, image_url, 0, TRUE FROM products WHERE image_url IS NOT NULL AND image_url <> '';
