CREATE TABLE payments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL REFERENCES orders (id),
    provider_ref VARCHAR(64)    NOT NULL UNIQUE,   -- order_id unik per percobaan bayar di sisi provider
    status       VARCHAR(20)    NOT NULL CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'EXPIRED')),
    amount       NUMERIC(14, 2) NOT NULL,
    token        VARCHAR(255),
    redirect_url VARCHAR(500),
    paid_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX idx_payments_order ON payments (order_id);
-- Paling banyak satu pembayaran PENDING per order: menjaga /pay tetap idempoten walau dipanggil bersamaan
CREATE UNIQUE INDEX uq_payments_one_pending_per_order ON payments (order_id) WHERE status = 'PENDING';
